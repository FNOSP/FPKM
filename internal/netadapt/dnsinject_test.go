	if !injectDNSPlatform {
		t.Skipf("当前平台 %s 不启用公共 DNS 注入", runtime.GOOS)
	}
	logs := captureLogs(t)
	resetDNSState(t)
	setStubResolvConf(t)
	oldTimeout := probeTimeout
