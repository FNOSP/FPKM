// resetDNSState 清空注入状态与解析器，保证各用例互不影响
func resetDNSState(t *testing.T) {
	t.Helper()
	mu.Lock()
	dnsServers = nil
	dnsChosen = ""
	mu.Unlock()
	net.DefaultResolver = &net.Resolver{}
	t.Cleanup(func() {
		mu.Lock()
		dnsServers = nil
		dnsChosen = ""
		mu.Unlock()
	})
}

// setStubResolvConf 把系统解析器配置指向临时文件，避免读写真实 /etc/resolv.conf
func setStubResolvConf(t *testing.T) {
	t.Helper()
	oldPath := resolvConfPath
	t.Cleanup(func() { resolvConfPath = oldPath })
	path := t.TempDir() + "/resolv.conf"
	if err := os.WriteFile(path, []byte(stubResolvConf), 0o644); err != nil {
		t.Fatalf("写入临时 resolv.conf 失败: %v", err)
	}
	resolvConfPath = path
}

// waitChosen 等待后台预探测把指定服务器固定下来
func waitChosen(server string, timeout time.Duration) bool {
	deadline := time.Now().Add(timeout)
	for time.Now().Before(deadline) {
		mu.Lock()
		chosen := dnsChosen
		mu.Unlock()
		if chosen == server {
			return true
		}
		time.Sleep(20 * time.Millisecond)
	}
	return false
}

// waitChosenAny 等待后台预探测固定任意一台服务器
func waitChosenAny(timeout time.Duration) bool {
	deadline := time.Now().Add(timeout)
	for time.Now().Before(deadline) {
		mu.Lock()
		chosen := dnsChosen
		mu.Unlock()
		if chosen != "" {
			return true
		}
		time.Sleep(20 * time.Millisecond)
	}
	return false
}

// captureLogs 把 [fpkm-net] 诊断日志重定向到内存，返回读取函数
func captureLogs(t *testing.T) func() string {
	t.Helper()
	buf := &safeBuf{}
	SetLogWriter(buf)
	t.Cleanup(func() { SetLogWriter(os.Stderr) })
	return buf.String
}

// safeBuf 是可并发写入的日志缓冲（探测在多个 goroutine 内并行写日志）
type safeBuf struct {
	mu sync.Mutex
	b  strings.Builder
}

func (s *safeBuf) Write(p []byte) (int, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.b.Write(p)
}

func (s *safeBuf) String() string {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.b.String()
}

// shrinkProbeTimeout 缩短探测超时，避免用例等待
func shrinkProbeTimeout(t *testing.T) {
	t.Helper()
	old := probeTimeout
	probeTimeout = 400 * time.Millisecond
	t.Cleanup(func() { probeTimeout = old })
}
