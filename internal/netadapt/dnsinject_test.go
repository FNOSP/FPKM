// 原样的实机 resolv.conf 片段：只指向 systemd-resolved 的本地存根，
// 对应 Linux 端日志里的 `lookup ... on 127.0.0.53:53: read udp ... i/o timeout`
const stubResolvConf = "# Generated by systemd-resolved\nnameserver 127.0.0.53\noptions edns0 trust-ad\nsearch lan\n"

func TestParseResolvConf(t *testing.T) {
	got := ParseResolvConf(stubResolvConf)
	if len(got) != 1 || got[0] != "127.0.0.53" {
		t.Fatalf("解析存根配置出错: %v", got)
	}

	multi := "# comment\nnameserver 8.8.8.8\n;nameserver 1.1.1.1\nnameserver 8.8.8.8\nnameserver 223.5.5.5:53\n\tdomain lan\n"
	got = ParseResolvConf(multi)
	if len(got) != 2 {
		t.Fatalf("应解析出 2 台去重后的服务器（; 开头为注释、重复项被去掉），实际: %v", got)
	}
	if got[0] != "8.8.8.8" || got[1] != "223.5.5.5:53" {
		t.Fatalf("解析顺序或内容异常: %v", got)
	}

	if n := len(ParseResolvConf("")); n != 0 {
		t.Fatalf("空内容应返回 0 条，实际 %d 条", n)
	}
}

func TestIsLoopbackServer(t *testing.T) {
	cases := map[string]bool{
		"127.0.0.53":    true,
		"127.0.0.1":     true,
		"127.0.0.53:53": true,
		"localhost":     true,
		"LOCALHOST:53":  true,
		"::1":           true,
		"[::1]:53":      true,
		"8.8.8.8":       false,
		"223.5.5.5:53":  false,
		"dns.example":   false,
	}
	for server, want := range cases {
		if got := IsLoopbackServer(server); got != want {
			t.Errorf("IsLoopbackServer(%q) = %v，期望 %v", server, got, want)
		}
	}
}

// TestFormatSystemDNS 覆盖注入前的诊断文案（纯函数，跨平台可测）：
// 只含本地存根 / 有真实服务器 / 内容为空
func TestFormatSystemDNS(t *testing.T) {
	// 只含本地存根：应明确指出「仅含本地存根」，这正是需要注入公共 DNS 的场景
	if got := formatSystemDNS(stubResolvConf); !strings.Contains(got, "仅含本地存根") {
		t.Fatalf("存根配置应描述为「仅含本地存根」，实际: %s", got)
	}

	// 有真实服务器：只描述，不下「需要注入」的判断（注入与否由本文件策略决定）
	got := formatSystemDNS("nameserver 8.8.8.8\nnameserver 127.0.0.53\n")
	if !strings.Contains(got, "系统 DNS") || strings.Contains(got, "仅含本地存根") {
		t.Fatalf("含真实服务器时描述异常: %s", got)
	}

	// 内容为空：描述为配置为空
	if got := formatSystemDNS(""); !strings.Contains(got, "为空") {
		t.Fatalf("空内容应描述为配置为空，实际: %s", got)
	}
}

// TestDescribeSystemDNS 覆盖本平台实际取用的诊断路径
func TestDescribeSystemDNS(t *testing.T) {
	oldPath := resolvConfPath
	t.Cleanup(func() { resolvConfPath = oldPath })
	logs := captureLogs(t)

	// Windows 上没有 /etc/resolv.conf：诊断信息应说明由系统解析器负责，不去读该文件
	if !hasResolvConf {
		if got := describeSystemDNS(); !strings.Contains(got, "Windows 系统解析器") {
			t.Fatalf("Windows 上应说明由系统解析器负责，实际: %s", got)
		}
		if out := logs(); strings.Contains(out, "读取") {
			t.Fatalf("Windows 上不应尝试读取 /etc/resolv.conf，实际日志: %s", out)
		}
		return
	}

	// 只含本地存根：应明确指出「仅含本地存根」，这正是需要注入公共 DNS 的场景
	path := t.TempDir() + "/stub.conf"
	if err := os.WriteFile(path, []byte(stubResolvConf), 0o644); err != nil {
		t.Fatalf("写入临时 resolv.conf 失败: %v", err)
	}
	resolvConfPath = path
	if got := describeSystemDNS(); !strings.Contains(got, "仅含本地存根") {
		t.Fatalf("存根配置应描述为「仅含本地存根」，实际: %s", got)
	}

	// 有真实服务器：只描述，不下「需要注入」的判断（注入与否由本文件策略决定）
	path = t.TempDir() + "/real.conf"
	if err := os.WriteFile(path, []byte("nameserver 8.8.8.8\nnameserver 127.0.0.53\n"), 0o644); err != nil {
		t.Fatalf("写入临时 resolv.conf 失败: %v", err)
	}
	resolvConfPath = path
	if got := describeSystemDNS(); !strings.Contains(got, "系统 DNS") || strings.Contains(got, "仅含本地存根") {
		t.Fatalf("含真实服务器时描述异常: %s", got)
	}

	// 读不到文件：配置为空，且留下读取失败日志
	resolvConfPath = t.TempDir() + "/missing.conf"
	if got := describeSystemDNS(); !strings.Contains(got, "为空") {
		t.Fatalf("读不到文件时应描述为配置为空，实际: %s", got)
	}
	if !strings.Contains(logs(), "读取") {
		t.Fatalf("读取失败应有日志，实际: %s", logs())
	}
}

