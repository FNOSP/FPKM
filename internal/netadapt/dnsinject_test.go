// TestPickUsableKeepsPreferenceOrder 并行探测仍按候选顺序取第一台可用者
func TestPickUsableKeepsPreferenceOrder(t *testing.T) {
	fakeA := startFakeDNS(t)
	fakeB := startFakeDNS(t)
	shrinkProbeTimeout(t)

	// 两台都可用：取列表里的第一台
	chosen, detail := pickUsable([]string{fakeA.addr, fakeB.addr}, func(server string) (bool, string) {
		return serverUsableWithin(server, "", probeTimeout)
	})
	if chosen != fakeA.addr {
		t.Fatalf("两台均可用时应按顺序取第一台 %s，实际 %q（%s）", fakeA.addr, chosen, detail)
	}

	// 首台不可达（192.0.2.1 为保留地址）：跳过并取下一台
	chosen, detail = pickUsable([]string{"192.0.2.1", fakeB.addr}, func(server string) (bool, string) {
		return serverUsableWithin(server, "", probeTimeout)
	})
	if chosen != fakeB.addr {
		t.Fatalf("应跳过不可达的首台并取 %s，实际 %q（%s）", fakeB.addr, chosen, detail)
	}

	// 全部不可达：返回空串与失败说明
	chosen, detail = pickUsable([]string{"192.0.2.1"}, func(server string) (bool, string) {
		return serverUsableWithin(server, "", probeTimeout)
	})
	if chosen != "" || detail == "" {
		t.Fatalf("全部不可达时应返回空串与说明，实际 chosen=%q detail=%q", chosen, detail)
	}
}

// TestInstallInjectedDNSUsesPublicDNS 是本轮修复的核心用例：
// 未注入 FPKM_DNS 时（Windows / Linux）直接注入公共 DNS，注入后域名解析可用。
// 用本地假 DNS 充当「可用公共 DNS」，不依赖外网。
func TestInstallInjectedDNSUsesPublicDNS(t *testing.T) {
	if !injectDNSPlatform {
		t.Skipf("当前平台 %s 不启用公共 DNS 注入", runtime.GOOS)
	}
	fake := startFakeDNS(t)
	shrinkProbeTimeout(t)
	logs := captureLogs(t)
	resetDNSState(t)
	setStubResolvConf(t)

	os.Unsetenv("FPKM_DNS")
	os.Unsetenv("FPKM_DNS_AUTO")
	os.Setenv("FPKM_PUBLIC_DNS", fake.addr)
	defer os.Unsetenv("FPKM_PUBLIC_DNS")

	before := net.DefaultResolver
	t.Cleanup(func() { net.DefaultResolver = before })

	InstallDNS("") // 走真实入口：未注入 FPKM_DNS → 注入公共 DNS

	if net.DefaultResolver == before {
		t.Fatal("未注入 FPKM_DNS 时应安装公共 DNS 解析器")
	}
	mu.Lock()
	injected := append([]string(nil), dnsServers...)
	mu.Unlock()
	if len(injected) != 1 || injected[0] != fake.addr {
		t.Fatalf("注入的服务器应为 %s，实际 %v", fake.addr, injected)
	}

	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	ips, err := net.DefaultResolver.LookupHost(ctx, "nas.hhxs2025.top")
	if err != nil {
		t.Fatalf("注入公共 DNS 后解析仍失败: %v", err)
	}
	if len(ips) == 0 || ips[0] != "127.0.0.1" {
		t.Fatalf("注入公共 DNS 后解析结果异常: %v", ips)
	}

	// 后台预探测应把可用服务器固定下来，后续解析不必再探测
	if !waitChosen(fake.addr, 3*time.Second) {
		t.Fatalf("后台预探测未固定可用服务器 %s；日志=%s", fake.addr, logs())
	}
	time.Sleep(50 * time.Millisecond)
	if out := logs(); !strings.Contains(out, "已注入公共 DNS 候选") || !strings.Contains(out, "公共 DNS 注入已生效") {
		t.Fatalf("注入日志不完整，实际: %s", out)
	}
	wantDNS := "仅含本地存根"
	if !hasResolvConf {
		wantDNS = "Windows 系统解析器"
	}
	if out := logs(); !strings.Contains(out, wantDNS) {
		t.Fatalf("应记录系统 DNS 现状（%s），实际: %s", wantDNS, out)
	}
}

